func TestRestoreIsAPrefixNotTheLastEdit(t *testing.T) {
	// The turn writes the same file three times. Only the state from before the
	// turn can be right; restoring the state before the last write would leave
	// two of the three edits in place, which is the bug a re-capture-per-write
	// implementation has.
	dir := newSessionDir(t)
	target := filepath.Join(dir, "f.txt")
	write(t, target, "v0")

	m := New()
	_, _ = m.Begin(dir, 0, "three edits")
	for i, v := range []string{"v1", "v2", "v3"} {
		if err := m.Capture(dir, target); err != nil {
			t.Fatalf("Capture %d: %v", i, err)
		}
		write(t, target, v)
	}

	cps, _ := m.List(dir)
	if got := len(cps[0].Files); got != 1 {
		t.Errorf("captured %d snapshots for one file, want 1", got)
	}
	Restore(&cps[0])
	if got := read(t, target); got != "v0" {
		t.Errorf("file = %q, want %q — the pre-turn contents", got, "v0")
	}
}

func TestSymlinksAreSkippedAndCounted(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("symlink creation needs elevation on Windows")
	}
	dir := newSessionDir(t)
	real := filepath.Join(dir, "real.txt")
	write(t, real, "real contents")
	link := filepath.Join(dir, "link.txt")
	if err := os.Symlink(real, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}

	m := New()
	_, _ = m.Begin(dir, 0, "edit through a link")
	_ = m.Capture(dir, link)

	cps, _ := m.List(dir)
	if got := cps[0].SkippedSymlinks; got != 1 {
		t.Errorf("SkippedSymlinks = %d, want 1", got)
	}

	out := Restore(&cps[0])
	if out.SkippedSymlinks != 1 {
		t.Errorf("Outcome.SkippedSymlinks = %d, want 1", out.SkippedSymlinks)
	}
	// The point of skipping: the target must be untouched, because following
	// the link would have rewritten a file the agent never named.
	if got := read(t, real); got != "real contents" {
		t.Errorf("the symlink target was modified: %q", got)
	}
	if !strings.Contains(out.String(), "symlink") {
		t.Errorf("Outcome.String() = %q, want it to name the skipped symlinks", out.String())
	}
}

func TestOversizedFilesAreSkippedNotTruncated(t *testing.T) {
	dir := newSessionDir(t)
	target := filepath.Join(dir, "big.bin")
	big := make([]byte, maxSnapshotBytes+1)
	for i := range big {
		big[i] = 'x'
	}
	write(t, target, string(big))

	m := New()
	_, _ = m.Begin(dir, 0, "rewrite a big file")
	_ = m.Capture(dir, target)
	write(t, target, "small")

	cps, _ := m.List(dir)
	out := Restore(&cps[0])

	if out.SkippedTooLarge != 1 || out.Restored != 0 {
		t.Errorf("Outcome = %+v, want 1 skipped and nothing restored", out)
	}
	// Restoring an empty snapshot would silently destroy the user's file.
	if got := read(t, target); got != "small" {
		t.Errorf("file = %q, want it left as the turn left it", got)
	}
}

