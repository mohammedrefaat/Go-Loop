func TestCleanupPeriodSweepsOldCheckpoints(t *testing.T) {
	dir := newSessionDir(t)
	now := time.Date(2026, 3, 10, 12, 0, 0, 0, time.UTC)
	m := New(WithCleanupPeriod(48*time.Hour))

	m.now = func() time.Time { return now.Add(-72 * time.Hour) }
	_, _ = m.Begin(dir, 1, "ancient")
	m.now = func() time.Time { return now.Add(-24 * time.Hour) }
	_, _ = m.Begin(dir, 2, "recent")
	m.now = func() time.Time { return now }
	// The next Begin is what runs the sweep — retention is not on a timer.
	_, _ = m.Begin(dir, 3, "now")

	cps, _ := m.List(dir)
	if len(cps) != 2 {
		t.Fatalf("got %d checkpoints, want 2 — the one older than the period must be gone", len(cps))
	}
	for _, cp := range cps {
		if cp.Label == "ancient" {
			t.Error("the checkpoint older than the cleanup period survived")
		}
	}
}

