func TestEndStopsFurtherCaptures(t *testing.T) {
	dir := newSessionDir(t)
	first := filepath.Join(dir, "first.txt")
	second := filepath.Join(dir, "second.txt")
	write(t, first, "1")
	write(t, second, "2")

	m := New()
	_, _ = m.Begin(dir, 0, "turn one")
	_ = m.Capture(dir, first)
	m.End(dir)
	_ = m.Capture(dir, second)

	cps, _ := m.List(dir)
	if got := len(cps[0].Files); got != 1 {
		t.Errorf("got %d snapshots, want 1 — the next turn's write must not join this one", got)
	}
	if m.Open(dir) {
		t.Error("Open() = true after End, want false")
	}
}

func TestBeginSupersedesAnUnfinishedCheckpoint(t *testing.T) {
	// A turn cancelled before it finishes still leaves its checkpoint open. The
	// next prompt must close it, or the two accumulate into one file and the
	// earlier index no longer describes a boundary.
	dir := newSessionDir(t)
	target := filepath.Join(dir, "f.txt")
	write(t, target, "v")

	m := New()
	_, _ = m.Begin(dir, 3, "cancelled turn")
	_ = m.Capture(dir, target)
	_, _ = m.Begin(dir, 9, "next turn")
	_ = m.Capture(dir, target)

	cps, _ := m.List(dir)
	if len(cps) != 2 {
		t.Fatalf("got %d checkpoints, want 2", len(cps))
	}
	for _, cp := range cps {
		if got := len(cp.Files); got != 1 {
			t.Errorf("checkpoint %s has %d snapshots, want 1", cp.ID, got)
		}
	}
	// The older one is listed first only after sorting; check by index instead.
	byIndex := map[int]int{}
	for _, cp := range cps {
		byIndex[cp.EventIndex] = len(cp.Files)
	}
	if byIndex[3] != 1 || byIndex[9] != 1 {
		t.Errorf("snapshots by index = %v, want one each at 3 and 9", byIndex)
	}
}

func TestListIsNewestFirst(t *testing.T) {
	dir := newSessionDir(t)
	m := New()
	base := time.Date(2026, 3, 1, 12, 0, 0, 0, time.UTC)
	for i := range 5 {
		m.now = func() time.Time { return base.Add(time.Duration(i) * time.Minute) }
		if _, err := m.Begin(dir, i, "turn"); err != nil {
			t.Fatalf("Begin %d: %v", i, err)
		}
	}

	cps, err := m.List(dir)
	if err != nil {
		t.Fatalf("List: %v", err)
	}
	if len(cps) != 5 {
		t.Fatalf("got %d checkpoints, want 5", len(cps))
	}
	for i := 1; i < len(cps); i++ {
		if cps[i-1].CreatedAt.Before(cps[i].CreatedAt) {
			t.Errorf("checkpoint %d (%s) is newer than the one before it (%s); order must be newest first",
				i, cps[i].CreatedAt, cps[i-1].CreatedAt)
		}
	}
}

