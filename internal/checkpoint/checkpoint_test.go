func TestOutcomeStringNamesEverySkip(t *testing.T) {
	tests := []struct {
		name string
		out  Outcome
		want []string
	}{
		{"nothing happened", Outcome{}, []string{"No files"}},
		{"restored", Outcome{Restored: 1}, []string{"1 file restored"}},
		{"removed", Outcome{Deleted: 2}, []string{"2 files removed"}},
		{"mixed", Outcome{Restored: 1, Deleted: 1, SkippedSymlinks: 3},
			[]string{"1 file restored", "1 file removed", "3 symlinks skipped"}},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			got := tc.out.String()
			for _, want := range tc.want {
				if !strings.Contains(got, want) {
					t.Errorf("Outcome.String() = %q, want it to contain %q", got, want)
				}
			}
		})
	}
}

func TestRestoreCountsFailuresWithoutGivingUp(t *testing.T) {
	// One unwritable path must not abandon the rest: the whole point of the
	// outcome counts is that the user is told exactly what did not come back.
	if runtime.GOOS == "windows" {
		t.Skip("the read-only directory trick does not apply to Windows")
	}
	dir := newSessionDir(t)
	locked := filepath.Join(dir, "locked")
	ok := filepath.Join(dir, "ok.txt")
	write(t, locked, "locked contents")
	write(t, ok, "ok contents")

	m := New()
	_, _ = m.Begin(dir, 0, "turn")
	_ = m.Capture(dir, locked)
	_ = m.Capture(dir, ok)

	if err := os.Chmod(dir, 0o500); err != nil {
		t.Skipf("chmod unavailable: %v", err)
	}
	t.Cleanup(func() { _ = os.Chmod(dir, 0o700) })

	cps, _ := m.List(dir)
	out := Restore(&cps[0])
	if out.Failed != 1 {
		t.Errorf("Failed = %d, want 1", out.Failed)
	}
	if out.Restored != 1 {
		t.Errorf("Restored = %d, want 1 — the writable file must still be restored", out.Restored)
	}
	if out.FirstErr == nil {
		t.Error("FirstErr is nil, want the underlying error for the diagnostic")
	}
}

